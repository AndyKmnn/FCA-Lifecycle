/**
 * Bakes germanyKreise.ts from a GeoJSON of the German Kreise.
 *
 * Run by hand when the outline needs regenerating; the checked-in artefact is
 * what ships, so the demo fetches nothing at runtime. See ATTRIBUTION.md.
 *
 *   curl -sSLO https://raw.githubusercontent.com/isellsoap/deutschlandGeoJSON/main/4_kreise/4_niedrig.geo.json
 *   node src/demo/scene1/make-germany-kreise.mjs 4_niedrig.geo.json
 *
 * The projection is pinned to the constants already baked into germanyStates.ts
 * rather than re-derived from this file's own bounding box. The two layers have
 * to sit on top of each other, and the site pin in regions.json is projected
 * through the same numbers - re-deriving would shift everything by a pixel or
 * two and there would be no obvious symptom, just a map slightly out of true.
 */
import fs from 'node:fs'

const K = 0.6266038114
const MIN_X = 3.679179
const MIN_Y = -55.056526
const SCALE = 128.425346
const WIDTH = 738
const HEIGHT = 1000

/**
 * Points closer than this to the previous one are dropped.
 *
 * Higher than the 1.2 px the states use: there are 434 shapes here rather than
 * 16, and every tenth of a pixel kept is paid for in the bundle. At 1.6 the
 * borders are still clean at the size this renders.
 */
const TOLERANCE = 1.6

const geo = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))

/** Stable id: state code plus a slug of the Kreis name. */
const STATE_CODES = {
  'Baden-Württemberg': 'BW',
  Bayern: 'BY',
  Berlin: 'BE',
  Brandenburg: 'BB',
  Bremen: 'HB',
  Hamburg: 'HH',
  Hessen: 'HE',
  'Mecklenburg-Vorpommern': 'MV',
  Niedersachsen: 'NI',
  'Nordrhein-Westfalen': 'NW',
  'Rheinland-Pfalz': 'RP',
  Saarland: 'SL',
  Sachsen: 'SN',
  'Sachsen-Anhalt': 'ST',
  'Schleswig-Holstein': 'SH',
  Thüringen: 'TH',
}

const slug = (s) =>
  s
    .toLowerCase()
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')

const seen = new Map()
const out = []

for (const f of geo.features) {
  const p = f.properties
  const state = STATE_CODES[p.NAME_1]
  if (!state) throw new Error(`unknown state: ${p.NAME_1}`)

  // GADM appends "Städte" to the urban districts; it is not part of the name.
  const name = p.NAME_3.replace(/\s+St(ä|ae)dte$/u, '').trim()

  let id = `${state}-${slug(name)}`
  // A handful of Kreis names repeat inside a state; keep ids unique and stable.
  const n = (seen.get(id) ?? 0) + 1
  seen.set(id, n)
  if (n > 1) id = `${id}-${n}`

  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates

  let sumX = 0
  let sumY = 0
  let count = 0
  const rings = []

  for (const poly of polys) {
    for (const ring of poly) {
      const pts = []
      for (const [lon, lat] of ring) {
        const X = +((lon * K - MIN_X) * SCALE).toFixed(1)
        const Y = +((-lat - MIN_Y) * SCALE).toFixed(1)
        sumX += X
        sumY += Y
        count++
        const last = pts[pts.length - 1]
        if (last && Math.abs(last[0] - X) < TOLERANCE && Math.abs(last[1] - Y) < TOLERANCE)
          continue
        pts.push([X, Y])
      }
      if (pts.length >= 3) rings.push(pts)
    }
  }
  if (rings.length === 0) continue

  const d = rings.map((pts) => `M${pts.map(([x, y]) => `${x} ${y}`).join('L')}Z`).join('')

  out.push({
    id,
    name,
    state,
    urban: p.ENGTYPE_3 === 'Urban district',
    // Centroid of the sampled outline - good enough to hang a label or a dot on.
    cx: +(sumX / count).toFixed(1),
    cy: +(sumY / count).toFixed(1),
    d,
  })
}

out.sort((a, b) => a.id.localeCompare(b.id))

const ts = `/**
 * German Kreis outlines for the connection explorer, pre-projected to one SVG
 * path each - 434 of them, which is the granularity the operator landscape
 * actually has. Germany has roughly 870 distribution system operators; a map of
 * sixteen federal states cannot say anything about where capacity is.
 *
 * Source: deutschlandGeoJSON (The Unlicense / public domain),
 * https://github.com/isellsoap/deutschlandGeoJSON - "4_kreise/4_niedrig",
 * itself derived from DIVA-GIS country data (http://www.diva-gis.org/gdata).
 * Generated by make-germany-kreise.mjs and checked in, so the demo makes no
 * network calls at runtime. See ATTRIBUTION.md in this folder.
 *
 * The projection matches germanyStates.ts exactly, so the two layers and the
 * site pin from regions.json all sit in the same space.
 */

export interface Kreis {
  id: string
  name: string
  /** Two-letter federal state code, as in public/data/regions.json. */
  state: string
  /** Kreisfreie Stadt rather than Landkreis. */
  urban: boolean
  /** Centroid of the outline, in map units. */
  cx: number
  cy: number
  /** The outline itself. */
  d: string
}

export const MAP_WIDTH = ${WIDTH}
export const MAP_HEIGHT = ${HEIGHT}

export const KREISE: Kreis[] = [
${out
  .map(
    (k) =>
      `  { id: '${k.id}', name: ${JSON.stringify(k.name)}, state: '${k.state}', urban: ${k.urban}, cx: ${k.cx}, cy: ${k.cy}, d: '${k.d}' },`,
  )
  .join('\n')}
]
`

fs.writeFileSync('src/demo/scene1/germanyKreise.ts', ts)

/* ------------------------------------------------------------------ operators
 *
 * The operator each Kreis's connection would be written by, and the terms it
 * writes. Emitted from this script rather than a separate one so the two can
 * never drift: an operator without an outline, or an outline without terms,
 * would be a hole in the map with no obvious cause.
 *
 * The names are regional rather than real. Germany's ~870 distribution system
 * operators are a matter of public record, but what any of them would write
 * into a flexible connection agreement is not - only a handful have published a
 * template at all. Putting an invented cap next to a real company's name in
 * front of a grid operator is a way to lose the room.
 *
 * Every figure below is drawn from a hash of the Kreis id, so the same id always
 * gets the same terms no matter what order the file is built in.
 */

/** xmur3 + mulberry32: a stable stream per id, independent of iteration order. */
function rngFor(id) {
  let h = 1779033703 ^ id.length
  for (let i = 0; i < id.length; i++) {
    h = Math.imul(h ^ id.charCodeAt(i), 3432918353)
    h = (h << 13) | (h >>> 19)
  }
  let a = (h ^= h >>> 16) >>> 0
  return () => {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const between = (r, lo, hi, dp = 1) => +(lo + r() * (hi - lo)).toFixed(dp)
const pick = (r, xs) => xs[Math.floor(r() * xs.length)]

const operators = out.map((k) => {
  const r = rngFor(k.id)

  /** How far along this operator is with low-voltage monitoring, 0-100. */
  const digitalisation = Math.round(
    between(r, k.urban ? 42 : 18, k.urban ? 96 : 82, 0),
  )

  /**
   * BNetzA confirmed in March 2026 that operators are not obliged to offer an
   * FCA; the Netzanschlusspaket would change that. Until it passes, some simply
   * do not - which is the single most useful thing the map can tell you.
   */
  const offersFca = digitalisation > 34 || r() < 0.18

  const limitType =
    !offersFca ? 'none'
    : digitalisation >= 74 ? 'fullyDynamic'
    : digitalisation >= 48 ? 'dynamic'
    : 'static'

  const monthsToConnect =
    limitType === 'fullyDynamic' ? Math.round(between(r, 6, 14, 0))
    : limitType === 'dynamic' ? Math.round(between(r, 10, 20, 0))
    : limitType === 'static' ? Math.round(between(r, 12, 26, 0))
    : Math.round(between(r, 28, 60, 0))

  const guaranteedMinimumMw = between(r, 1.5, 3.0)
  const capMw =
    limitType === 'fullyDynamic' ? between(r, 4.4, 6.0)
    : limitType === 'dynamic' ? between(r, 3.2, 4.8)
    : limitType === 'static' ? between(r, 2.8, 4.2)
    : 0

  return {
    id: k.id,
    name: `${k.urban ? 'Stadtnetz' : 'Netz Landkreis'} ${k.name}`,
    kreis: k.name,
    state: k.state,
    urban: k.urban,
    offersFca,
    limitType,
    capMw,
    guaranteedMinimumMw: limitType === 'none' ? 0 : guaranteedMinimumMw,
    monthsToConnect,
    monthsToFirm: monthsToConnect + Math.round(between(r, 18, 40, 0)),
    noticePeriod:
      limitType === 'fullyDynamic' ? 'day-ahead'
      : limitType === 'dynamic' ? 'seasonal schedule'
      : limitType === 'static' ? 'fixed, no notice'
      : 'not offered',
    maxCurtailmentHours: limitType === 'none' ? 0 : Math.round(between(r, 200, 1200, 0) / 10) * 10,
    compensationAboveCap: limitType === 'none' ? false : r() < 0.38,
    bkzEurPerKw: Math.round(between(r, 60, 190, 0)),
    voltageLevel: pick(r, ['MS', 'MS', 'MS', 'HS/MS', 'HS/MS', 'HS']),
    headroomMw: between(r, k.urban ? 0.4 : 1.2, k.urban ? 9 : 26),
    digitalisation,
  }
})

/**
 * The Kreis the site sits in is not left to the hash.
 *
 * Scene 3 replays a year against limits.json, which was generated for a fully
 * dynamic day-ahead regime connecting in 8 months. If the explorer rolled this
 * operator a static cap and 14 months, the two screens would state different
 * terms for the same connection and the demo would fall apart the moment
 * anybody compared them. So the home operator is read from the scenario files
 * rather than generated, and the rest of the country is generated around it.
 */
const HOME_ID = 'BY-freising'
const limits = JSON.parse(fs.readFileSync('public/data/limits.json', 'utf8'))
const districts = JSON.parse(fs.readFileSync('public/data/districts.json', 'utf8'))
const homeDistrict = districts.districts.find((d) => d.limitType === 'fullyDynamic')
const home = operators.find((o) => o.id === HOME_ID)
if (!home) throw new Error(`home Kreis ${HOME_ID} not in the outline set`)
Object.assign(home, {
  offersFca: true,
  limitType: 'fullyDynamic',
  capMw: limits.meta.defaultLimitMw,
  guaranteedMinimumMw: limits.meta.guaranteedMinimumMw,
  monthsToConnect: homeDistrict.monthsToConnect,
  monthsToFirm: homeDistrict.monthsToFirm,
  noticePeriod: limits.meta.noticePeriod,
  digitalisation: 88,
})

const json = {
  meta: {
    homeId: HOME_ID,
    note:
      'Regional operator names and generated terms. Germany has roughly 870 distribution ' +
      'system operators; what each would write into a flexible connection agreement is not ' +
      'public, so the terms here are constructed and the names are regional rather than real.',
    year: 2026,
    requestedMw: 6,
    count: operators.length,
  },
  operators,
}

fs.writeFileSync('public/data/operators.json', JSON.stringify(json))

const byType = {}
for (const o of operators) byType[o.limitType] = (byType[o.limitType] ?? 0) + 1
console.log(
  `kreise ${out.length} | urban ${out.filter((k) => k.urban).length} | bytes ${ts.length}`,
)
console.log('operators', operators.length, byType)
