/**
 * Bakes germanyStates.ts from a GeoJSON of the 16 German federal states.
 *
 * Run by hand when the outline needs regenerating; the checked-in artefact is
 * what ships, so the demo fetches nothing at runtime. See ATTRIBUTION.md.
 *
 *   curl -sSLO https://raw.githubusercontent.com/isellsoap/deutschlandGeoJSON/main/2_bundeslaender/4_niedrig.geo.json
 *   node src/demo/scene1/make-germany-states.mjs 4_niedrig.geo.json
 */
import fs from 'node:fs'

const geo = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))

/** Equirectangular, x compressed by cos(lat0) - good enough for one country. */
const LAT0 = 51.2
const K = Math.cos((LAT0 * Math.PI) / 180)
const HEIGHT = 1000

let minX = Infinity
let maxX = -Infinity
let minY = Infinity
let maxY = -Infinity
const shapes = []

for (const f of geo.features) {
  const code = f.properties.id.replace('DE-', '')
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  const rings = []
  for (const poly of polys) {
    for (const ring of poly) {
      rings.push(
        ring.map(([lon, lat]) => {
          const x = lon * K
          const y = -lat
          if (x < minX) minX = x
          if (x > maxX) maxX = x
          if (y < minY) minY = y
          if (y > maxY) maxY = y
          return [x, y]
        }),
      )
    }
  }
  shapes.push({ code, rings })
}

const scale = HEIGHT / (maxY - minY)
const WIDTH = Math.round((maxX - minX) * scale)

const paths = shapes.map(({ code, rings }) => {
  const d = rings
    .map((pts) => {
      // Drop points closer than 1.2 px to the previous one - invisible at this size.
      const out = []
      for (const [x, y] of pts) {
        const X = +((x - minX) * scale).toFixed(1)
        const Y = +((y - minY) * scale).toFixed(1)
        const last = out[out.length - 1]
        if (last && Math.abs(last[0] - X) < 1.2 && Math.abs(last[1] - Y) < 1.2) continue
        out.push([X, Y])
      }
      if (out.length < 3) return ''
      return `M${out.map(([x, y]) => `${x} ${y}`).join('L')}Z`
    })
    .filter(Boolean)
    .join('')
  return { code, d }
})

const ts = `/**
 * German federal state outlines for scene 1, pre-projected to an SVG path each.
 *
 * Source: deutschlandGeoJSON (The Unlicense / public domain),
 * https://github.com/isellsoap/deutschlandGeoJSON - "2_bundeslaender/4_niedrig",
 * itself derived from DIVA-GIS country data (http://www.diva-gis.org/gdata).
 * Generated by make-germany-states.mjs and checked in, so the demo makes no
 * network calls at runtime. See ATTRIBUTION.md in this folder.
 */

export const MAP_WIDTH = ${WIDTH}
export const MAP_HEIGHT = ${HEIGHT}

/** Equirectangular, x compressed by cos(${LAT0}deg). Matches the baked paths. */
export function project(lon: number, lat: number): { x: number; y: number } {
  return {
    x: (lon * ${K.toFixed(10)} - ${minX.toFixed(6)}) * ${scale.toFixed(6)},
    y: (-lat - ${minY.toFixed(6)}) * ${scale.toFixed(6)},
  }
}

/** State code (as in public/data/regions.json) to outline path. */
export const STATE_PATHS: Record<string, string> = {
${paths.map((p) => `  ${p.code}: '${p.d}',`).join('\n')}
}
`
fs.writeFileSync('src/demo/scene1/germanyStates.ts', ts)
console.log('viewBox', WIDTH, HEIGHT, '| states', paths.length, '| bytes', ts.length)
