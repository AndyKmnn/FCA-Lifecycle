/**
 * Bakes europeOutline.ts from Natural Earth 1:110m country outlines.
 *
 * Run by hand when the outline needs regenerating; the checked-in artefact is
 * what ships, so the demo fetches nothing at runtime. See ATTRIBUTION.md.
 *
 *   node src/demo/scene1/make-europe-outline.mjs <ne_110m_admin_0_countries.geojson>
 */
import fs from 'node:fs'

const src = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))

/** Western and central Europe: enough context for Germany without the whole continent. */
const BBOX = { lonMin: -11, lonMax: 31, latMin: 35, latMax: 60 }
const LAT0 = 52
const K = Math.cos((LAT0 * Math.PI) / 180)
const HEIGHT = 1000

const inBox = (lon, lat) =>
  lon >= BBOX.lonMin && lon <= BBOX.lonMax && lat >= BBOX.latMin && lat <= BBOX.latMax

const x0 = BBOX.lonMin * K
const y0 = -BBOX.latMax
const scale = HEIGHT / (BBOX.latMax - BBOX.latMin)
const WIDTH = Math.round((BBOX.lonMax - BBOX.lonMin) * K * scale)

const shapes = []
for (const f of src.features) {
  if (f.properties.CONTINENT !== 'Europe') continue
  const code = f.properties.ISO_A2_EH || f.properties.ISO_A2
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  const rings = []
  for (const poly of polys) {
    for (const ring of poly) {
      // Keep a ring only if some of it is in view; clamp the rest to the frame.
      if (!ring.some(([lon, lat]) => inBox(lon, lat))) continue
      const pts = []
      for (const [lon, lat] of ring) {
        const cl = Math.min(BBOX.lonMax, Math.max(BBOX.lonMin, lon))
        const ca = Math.min(BBOX.latMax, Math.max(BBOX.latMin, lat))
        const X = +((cl * K - x0) * scale).toFixed(1)
        const Y = +((-ca - y0) * scale).toFixed(1)
        const last = pts[pts.length - 1]
        if (last && Math.abs(last[0] - X) < 1.5 && Math.abs(last[1] - Y) < 1.5) continue
        pts.push([X, Y])
      }
      if (pts.length >= 3) rings.push(pts)
    }
  }
  if (rings.length) shapes.push({ code, d: rings.map((p) => `M${p.map(([x, y]) => `${x} ${y}`).join('L')}Z`).join('') })
}

const ts = `/**
 * Western and central Europe, pre-projected to one SVG path per country.
 *
 * Source: Natural Earth 1:110m Admin 0 Countries - public domain (CC0).
 * https://www.naturalearthdata.com/
 * Generated by make-europe-outline.mjs and checked in, so the demo makes no
 * network calls at runtime. See ATTRIBUTION.md in this folder.
 */

export const EUROPE_WIDTH = ${WIDTH}
export const EUROPE_HEIGHT = ${HEIGHT}

/** The country the demo zooms into. */
export const HOME_COUNTRY = 'DE'

/** ISO 3166-1 alpha-2 to outline path. */
export const EUROPE_PATHS: Record<string, string> = {
${shapes.map((s) => `  ${/^[A-Z]{2}$/.test(s.code) ? s.code : `'${s.code}'`}: '${s.d}',`).join('\n')}
}
`
fs.writeFileSync('src/demo/scene1/europeOutline.ts', ts)
console.log('viewBox', WIDTH, HEIGHT, '| countries', shapes.length, '| bytes', ts.length)
